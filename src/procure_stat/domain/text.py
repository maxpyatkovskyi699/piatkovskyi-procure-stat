# Зміна A: перша нова функція (реверс слова)
def reverse_text(raw: str) -> str:
    return raw[::-1]


def normalize_title(raw: str) -> str:
    """Нормалізує назву закупівлі.

    Видаляє зайві пробіли, приводить текст до нижнього регістру
    та об'єднує слова поодинокими пробілами.

    Args:
        raw (str): Початковий рядок із назвою.

    Returns:
        str: Нормалізований рядок або порожній рядок, якщо вхідні дані порожні.
    """
    # Перевірка на None або порожній рядок (після видалення зовнішніх пробілів)
    if not raw or not raw.strip():
        return ""

    # Очищення від крайових пробілів, приведення до нижнього регістру та нормалізація внутрішніх пробілів
    cleaned_raw = raw.strip()
    return " ".join(cleaned_raw.split()).lower()


# Зміна B: друга нова функція (перша літера велика)
def capitalize_text(raw: str) -> str:
    return raw.capitalize()
